// ===================================================
// プラットフォーム手数料
// ---------------------------------------------------
// 表示（マイページの受取額）と実際に取る額がずれないよう、必ず sellerNet から
// 逆算する。ここで独自に price * 0.1 と書くと、端数処理の違いで1円ずれる。
// ===================================================

import { sellerNet } from "@/lib/constants";

/**
 * 買い手への請求額から、プラットフォームが受け取る手数料（円）を求める。
 * 残り（sellerNet）が出品者の受取額として送金される。
 *
 * ※ Stripe の決済手数料（日本 3.6%）はここには含まれず、プラットフォーム残高から
 *   別途引かれる。1,000円の本なら 手数料100円 − Stripe 36円 = 実質64円。
 *   低価格帯ではチャージバック1件で吹き飛ぶ水準なので、料率は PO 判断事項。
 */
export function applicationFeeAmount(priceJpy: number): number {
  return priceJpy - sellerNet(priceJpy);
}
